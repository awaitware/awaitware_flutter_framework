import 'package:flutter/widgets.dart';

/// Tailwind CSS-inspired `backdrop-filter: contrast()` utilities for Flutter.
///
/// Docs: https://tailwindcss.com/docs/backdrop-filter-contrast
///
/// **No-op.** Same reason as `backdrop-filter-brightness` — see
/// `backdrop_filter_extensions.dart`. These methods exist only so this doc
/// page has a corresponding file; they return the widget unchanged.
extension BackdropFilterContrastExtensions on Widget {
  Widget backdropContrast0() => this;
  Widget backdropContrast50() => this;
  Widget backdropContrast75() => this;
  Widget backdropContrast100() => this;
  Widget backdropContrast125() => this;
  Widget backdropContrast150() => this;
  Widget backdropContrast200() => this;
}
