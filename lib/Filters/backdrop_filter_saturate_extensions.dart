import 'package:flutter/widgets.dart';

/// Tailwind CSS-inspired `backdrop-filter: saturate()` utilities for Flutter.
///
/// Docs: https://tailwindcss.com/docs/backdrop-filter-saturate
///
/// **No-op.** Same reason as `backdrop-filter-brightness` — see
/// `backdrop_filter_extensions.dart`. These methods exist only so this doc
/// page has a corresponding file; they return the widget unchanged.
extension BackdropFilterSaturateExtensions on Widget {
  Widget backdropSaturate0() => this;
  Widget backdropSaturate50() => this;
  Widget backdropSaturate100() => this;
  Widget backdropSaturate150() => this;
  Widget backdropSaturate200() => this;
}
